#!/usr/bin/env python3
"""Generates the embedded Kotlin country and geo data from a pinned dr5hn release.

Run by hand with `python3 -I scripts/generate_data.py`; the output is committed.
To update the data, change RELEASE, COMMIT and the EXPECTED_* totals, then re-run.
"""

import json
import urllib.request
from pathlib import Path

RELEASE = "v5.2.0-export.1"
COMMIT = "9b255c45fc53e02a8dff547d88558d4fe91784d5"
SOURCE_URL = (
    "https://raw.githubusercontent.com/dr5hn/countries-states-cities-database/"
    f"{COMMIT}/json/countries%2Bstates%2Bcities.json"
)
ROOT = Path(__file__).resolve().parent.parent
COUNTRY_FILE = ROOT / "countries/src/commonMain/kotlin/com/mukeshsolanki/countries/generated/CountryData.kt"
GEO_FILE = ROOT / "countries-geo/src/commonMain/kotlin/com/mukeshsolanki/countries/geo/generated/GeoData.kt"

FIELD_SEPARATOR = "\u001f"
ITEM_SEPARATOR = "\u001e"
RECORD_SEPARATOR = "\n"
FORBIDDEN_CHARS = {FIELD_SEPARATOR, ITEM_SEPARATOR, "\n", "\r"}
MAX_CHUNK_BYTES = 60_000
EXPECTED_COUNTRIES = 250
EXPECTED_STATES = 5_327
EXPECTED_STATE_CITIES = 152_375
EXPECTED_DIRECT_CITIES = 3
HEADER = (
    f"// Generated by scripts/generate_data.py from dr5hn/countries-states-cities-database {RELEASE} "
    f"({COMMIT}). Data licensed under ODbL-1.0. Do not edit.\n"
)


def fetch_countries():
    """Downloads and parses the combined dataset from the pinned commit."""
    with urllib.request.urlopen(SOURCE_URL, timeout=300) as response:
        return json.load(response)


def clean(value):
    """Returns a value unchanged after asserting it cannot corrupt the encoding."""
    bad = FORBIDDEN_CHARS.intersection(value)
    if bad:
        raise ValueError(f"Separator character in value: {value!r}")
    return value


def phone_code(raw):
    """Converts an upstream phone code to +digits, failing on anything else."""
    if not raw.isdigit():
        raise ValueError(f"Unparseable phone code: {raw!r}")
    return f"+{raw}"


def coordinate(raw, limit):
    """Validates a coordinate string against its range and returns it unchanged."""
    if abs(float(raw)) > limit:
        raise ValueError(f"Coordinate out of range: {raw!r}")
    return raw


def encode_translations(translations):
    """Encodes non-empty translations as alternating language tag and value items."""
    items = []
    for tag, value in translations.items():
        if value and value.strip():
            items += [clean(tag), clean(value)]
    return ITEM_SEPARATOR.join(items)


def encode_country(country):
    """Encodes one country as a record; an empty capital decodes to null."""
    fields = [
        clean(country["name"]),
        clean(country["iso2"]),
        clean(country["iso3"]),
        phone_code(country["phonecode"]),
        clean(country["capital"] or ""),
        clean(country["currency"]),
        clean(country["currency_name"]),
        clean(country["currency_symbol"]),
        clean(country["emoji"]),
        coordinate(country["latitude"], 90),
        coordinate(country["longitude"], 180),
        encode_translations(country["translations"]),
    ]
    return FIELD_SEPARATOR.join(fields)


def unique_city_names(cities):
    """Returns city names without duplicates, keeping their order."""
    return list(dict.fromkeys(clean(city["name"]) for city in cities))


def encode_state(state):
    """Encodes one state as a record of name, code, type and city names."""
    return FIELD_SEPARATOR.join(
        [
            clean(state["name"]),
            clean(state["iso2"]),
            clean(state["type"] or ""),
            ITEM_SEPARATOR.join(unique_city_names(state["cities"])),
        ]
    )


def modified_utf8_size(char):
    """Returns the size of a code point in a JVM class file constant."""
    return 6 if ord(char) > 0xFFFF else len(char.encode("utf-8"))


def split_chunks(text):
    """Splits text on code point boundaries into chunks that fit a JVM string constant."""
    chunks, current, size = [], [], 0
    for char in text:
        char_size = modified_utf8_size(char)
        if size + char_size > MAX_CHUNK_BYTES:
            chunks.append("".join(current))
            current, size = [], 0
        current.append(char)
        size += char_size
    chunks.append("".join(current))
    return chunks


def kotlin_literal(text):
    """Renders text as a Kotlin string literal, escaping templates and control characters."""
    escapes = {"\\": "\\\\", '"': '\\"', "$": "\\$", "\n": "\\n"}
    rendered = []
    for char in text:
        if char in escapes:
            rendered.append(escapes[char])
        elif ord(char) < 0x20 or ord(char) == 0x7F:
            rendered.append(f"\\u{ord(char):04X}")
        else:
            rendered.append(char)
    return '"' + "".join(rendered) + '"'


def kotlin_list(text):
    """Renders text as a Kotlin listOf call over its chunks."""
    return "listOf(" + ", ".join(kotlin_literal(chunk) for chunk in split_chunks(text)) + ")"


def write_file(path, content):
    """Writes generated UTF-8 source, creating parent directories."""
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(content, encoding="utf-8")


def country_source(records):
    """Builds the source of the generated countries file."""
    body = kotlin_list(RECORD_SEPARATOR.join(records))
    return (
        f"{HEADER}package com.mukeshsolanki.countries.generated\n\n"
        "/** Returns the encoded country records, split into JVM-safe chunks. */\n"
        f"internal fun countryChunks(): List<String> = {body}\n"
    )


def geo_source(state_branches, direct_branches):
    """Builds the source of the generated geo file."""
    states = "".join(f'    "{iso3}" -> {kotlin_list(text)}\n' for iso3, text in state_branches)
    direct = "".join(f'    "{iso3}" -> {kotlin_list(text)}\n' for iso3, text in direct_branches)
    return (
        f"{HEADER}package com.mukeshsolanki.countries.geo.generated\n\n"
        "/** Returns the encoded state records of a country, empty when it has no states. */\n"
        "internal fun geoChunks(iso3: String): List<String> = when (iso3) {\n"
        f"{states}    else -> emptyList()\n}}\n\n"
        "/** Returns the encoded names of cities listed directly on a country, outside any state. */\n"
        "internal fun directCityChunks(iso3: String): List<String> = when (iso3) {\n"
        f"{direct}    else -> emptyList()\n}}\n"
    )


def check_totals(countries, states, state_cities, direct_cities):
    """Fails when the source differs from the profiled release."""
    actual = (countries, states, state_cities, direct_cities)
    expected = (EXPECTED_COUNTRIES, EXPECTED_STATES, EXPECTED_STATE_CITIES, EXPECTED_DIRECT_CITIES)
    if actual != expected:
        raise ValueError(f"Unexpected totals {actual}, expected {expected}")


def main():
    """Downloads, validates and encodes the data, then writes both Kotlin files."""
    countries = fetch_countries()
    records, state_branches, direct_branches = [], [], []
    state_count = state_city_count = direct_city_count = kept_city_count = 0
    for country in countries:
        records.append(encode_country(country))
        states = country["states"]
        if states:
            state_branches.append(
                (country["iso3"], RECORD_SEPARATOR.join(encode_state(state) for state in states))
            )
        state_count += len(states)
        state_city_count += sum(len(state["cities"]) for state in states)
        kept_city_count += sum(len(unique_city_names(state["cities"])) for state in states)
        direct = unique_city_names(country["cities"])
        if direct:
            direct_branches.append((country["iso3"], ITEM_SEPARATOR.join(direct)))
        direct_city_count += len(country["cities"])

    check_totals(len(countries), state_count, state_city_count, direct_city_count)
    write_file(COUNTRY_FILE, country_source(records))
    write_file(GEO_FILE, geo_source(state_branches, direct_branches))
    print(
        f"countries={len(countries)} states={state_count} cities_in_states={kept_city_count} "
        f"direct_cities={direct_city_count} duplicate_names_removed={state_city_count - kept_city_count} "
        f"countries_with_states={len(state_branches)}"
    )


if __name__ == "__main__":
    main()
